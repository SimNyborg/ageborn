/**
 * The unit sheet sizes the memory governor plans with (`unitSheetPixels.gen.ts`, 2026-10-18) match the
 * installed sheets: every unit sheet's four images (HD core, HD extras, 1x core, 1x extras) by the
 * `meta.size` of their JSON. After new or re-rendered unit art, regenerate the table:
 *
 *   UPDATE_SHEET_PIXELS=1 npx vitest run src/visuals/test/unitSheetPixels.test.ts
 */
import { describe, expect, it } from 'vitest';
import { UNIT_SHEET_PIXELS } from '../unitSheetPixels.gen';

/** The test runs in Node; `src` has no Node types, so its two Node calls are reached untyped. */
const env = (globalThis as { process?: { env: Record<string, string | undefined> } }).process?.env ?? {};
async function writeText(url: URL, text: string): Promise<void> {
  const fs = (await import(/* @vite-ignore */ ['node', 'fs'].join(':'))) as { writeFileSync(path: URL, data: string): void };
  fs.writeFileSync(url, text);
}

interface SheetMeta {
  meta: { size: { w: number; h: number } };
}
/** Every unit sheet JSON (core, extras, HD and 1x), read at test time (never bundled into the game). */
const JSONS = import.meta.glob<SheetMeta>('/public/art/units/*/*.json', { eager: true, import: 'default' });

/** `<age>/<slug>` → [HD core, HD extras, 1x core, 1x extras] in pixels (0 for an image that is not installed). */
function installed(): Record<string, [number, number, number, number]> {
  const px = (path: string): number => {
    const s = JSONS[path]?.meta.size;
    return s ? s.w * s.h : 0;
  };
  const out: Record<string, [number, number, number, number]> = {};
  for (const path of Object.keys(JSONS).sort()) {
    const m = /^\/public\/art\/units\/([a-z]+)\/([a-z0-9_]+)\.json$/.exec(path);
    if (!m) continue;
    const dir = `/public/art/units/${m[1]}/${m[2]}`;
    out[`${m[1]}/${m[2]}`] = [px(`${dir}.hd.json`), px(`${dir}.x.hd.json`), px(`${dir}.json`), px(`${dir}.x.json`)];
  }
  return out;
}

describe('unit sheet sizes (memory governor)', () => {
  it('the table matches the installed sheets (else regenerate it, see the header)', async () => {
    const want = installed();
    if (env['UPDATE_SHEET_PIXELS'] === '1') {
      const rows = Object.entries(want).map(([k, v]) => `  '${k}': [${v.join(', ')}],`);
      await writeText(
        new URL('../unitSheetPixels.gen.ts', import.meta.url),
        [
          '// Generated by `UPDATE_SHEET_PIXELS=1 npx vitest run src/visuals/test/unitSheetPixels.test.ts` from the',
          '// `meta.size` of public/art/units/**. Do not edit by hand.',
          '',
          '/** Pixels (w x h) of each unit sheet\'s images by `<age>/<slug>`: HD core, HD extras, 1x core, 1x extras. */',
          'export const UNIT_SHEET_PIXELS: Readonly<Record<string, readonly [number, number, number, number]>> = {',
          ...rows,
          '};',
          '',
        ].join('\n'),
      );
      return;
    }
    expect(Object.keys(UNIT_SHEET_PIXELS).sort()).toEqual(Object.keys(want).sort());
    for (const [k, v] of Object.entries(want)) expect(UNIT_SHEET_PIXELS[k], k).toEqual(v);
  });

  it('every unit has all four images, and an HD copy holds about four times the pixels of its 1x copy', () => {
    for (const [k, [hd, hdx, sd, sdx]] of Object.entries(UNIT_SHEET_PIXELS)) {
      expect(hd > 0 && hdx > 0 && sd > 0 && sdx > 0, k).toBe(true);
      // packing differs a little between the two densities; the governor plans with the real numbers
      expect((hd + hdx) / (sd + sdx), k).toBeGreaterThan(2.5);
      expect((hd + hdx) / (sd + sdx), k).toBeLessThan(6);
    }
  });
});
